// Writes apps/<app>/web/src/api.gen.ts: the types of the app's REST API, taken
// from the OpenAPI document the server builds from its Zod schemas.
// Runs after tsc (it imports the compiled server). Use with openapi-fetch:
//   createClient<paths>()
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

process.env.NODE_ENV = "test"; // no request logging while the server is built
const { openApiSpec } = await import("../packages/core/dist/index.js");

for (const app of ["tickvana"]) {
  const { definition } = await import(`../apps/${app}/dist/app.js`);
  const ast = await openapiTS(await openApiSpec(definition));
  const file = new URL(`../apps/${app}/web/src/api.gen.ts`, import.meta.url);
  await writeFile(
    file,
    `// Generated by scripts/gen-api.mjs. Do not edit.\n\n${astToString(ast)}`,
  );
  console.log(`${app}: api.gen.ts written`);
}
